const ROWS = 5;

export function NumberAscii(number : number) {
  const chars = String(number).split('');
  const lines = Array.from({ length: ROWS }, (_, row) =>
    chars.map((c) => DIGITS[c][row]).join(' ')
  );

  return (
    <div style={{ fontFamily: 'monospace', whiteSpace: 'pre', lineHeight: 1.1 }}>
      {lines.join('\n')}
    </div>
  );
}